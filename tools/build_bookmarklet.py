#!/usr/bin/env python3
"""Build the Sync bookmark for the published app from tools/sync_bookmarklet.js.

The published bookmark is a short loader (no long paste on phones, nothing for a phone's
bookmark editor to truncate or mangle) that adds <site>/sync.js to the DUPR page. This writes
that sync.js (the source with the app URL / player ids filled in) and injects the loader into
index.html as the Sync bookmark's href. Run after editing the bookmarklet source or site.json:

    python tools/build_bookmarklet.py

tools/serve_local.py imports bookmark_href() / inject() to build a local copy's bookmark on
the fly: there it is the whole script inlined (comments and indentation stripped, escaped for
a javascript: URL in an HTML attribute), since an https DUPR page may refuse a script from
http://localhost. The committed index.html always keeps the published loader.
"""
import io, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "tools", "sync_bookmarklet.js")
HTML = os.path.join(ROOT, "index.html")

# The published app comes from site.json: its address, and optionally a DUPR player it is
# pinned to (duprId numeric / duprCode short). Both empty = whoever is logged in to DUPR.
_site = json.load(io.open(os.path.join(ROOT, "site.json"), encoding="utf-8"))
PUBLISHED = {"app": _site["app"], "id": str(_site.get("duprId") or ""), "code": _site.get("duprCode") or ""}
ANCHOR = re.compile(r'(<a class="bm" id="syncBm" href=")[^"]*(")')


def _js_str(v):
    s = str(v)
    assert re.fullmatch(r"[A-Za-z0-9:/?=._\-]*", s), f"unexpected characters in bookmarklet value {s!r}"
    return s


def sync_js(app, id="", code=""):
    code_js = io.open(SRC, encoding="utf-8").read()
    for key, val in (("__APP__", app), ("__ID__", id), ("__CODE__", code)):
        code_js = code_js.replace(key, _js_str(val))
    return code_js


def loader_href(app):
    base = _js_str(app.split("?")[0])
    src = base + ("" if base.endswith("/") else "/") + "sync.js"
    js = ("(()=>{const s=document.createElement('script');s.src='" + src + "?'+Date.now();"
          "s.onerror=()=>alert('PB Sync could not load " + src + ". Check your connection and try again.');"
          "document.body.appendChild(s);})()")
    return "javascript:" + js


def bookmark_href(app, id="", code=""):
    code_js = sync_js(app, id, code)
    lines = []
    for ln in code_js.splitlines():
        s = ln.strip()
        if not s or s.startswith("//"):
            continue
        lines.append(s)
    js = " ".join(lines)
    assert "//" not in re.sub(r"https?://", "", js), "inline // comment would swallow the rest"
    return "javascript:" + js.replace("%", "%25").replace("&", "&amp;").replace('"', "&quot;")


def inject(html, href):
    new, count = ANCHOR.subn(lambda m: m.group(1) + href + m.group(2), html)
    assert count == 1, f"expected one sync bookmark anchor, found {count}"
    return new


if __name__ == "__main__":
    head = "// GENERATED by tools/build_bookmarklet.py from tools/sync_bookmarklet.js. Don't edit here.\n"
    io.open(os.path.join(ROOT, "sync.js"), "w", encoding="utf-8", newline="\n").write(head + sync_js(**PUBLISHED))
    href = loader_href(PUBLISHED["app"])
    html = io.open(HTML, encoding="utf-8").read()
    io.open(HTML, "w", encoding="utf-8", newline="").write(inject(html, href))
    print(f"Wrote sync.js and injected the loader bookmark ({len(href)} chars) into index.html")
